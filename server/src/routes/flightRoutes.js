import authorize from '../middleware/authorize.js';
import FlightRequest from '../models/FlightRequest.js';
import { quoteHandlers } from '../controllers/quoteController.js';
import { Router } from 'express';
import * as controller from '../controllers/flightController.js';
import authenticate from '../middleware/authenticate.js';
import validate from '../middleware/validate.js';
import validateId from '../middleware/validateId.js';
import { schemas } from '../validators/index.js';
const router = Router();
router.param('id', validateId);
router.use(authenticate);
router.get('/', controller.list);
router.post('/', validate(schemas.flight), controller.create);
router.patch('/:id/status', validate(schemas.flightStatus), controller.update);
const quotes = quoteHandlers(FlightRequest, { booking: false });
router.post('/:id/quote', authorize('admin'), validate(schemas.quoteOffer), quotes.offer);
router.post('/:id/quote/respond', validate(schemas.quoteResponse), quotes.respond);
export default router;
